#!/usr/bin/env python3
"""Pokémon Trinacria - generates the engine lookup tables from CSV files.

Inputs (run from the pokeheartgold root):
    data/trinacria/post_resignation_banks.csv   columns: pre_bank,post_bank,note
    data/trinacria/etna_ash_zone.csv            columns: kind,symbol   (kind = map | flypoint)
Outputs:
    include/trinacria/post_resignation_banks.h  -> sTrinacriaPostBanks[]   (used by src/script_manager.c)
    include/trinacria/etna_ash_zone.h           -> sTrinacriaEtnaAshMaps[], sTrinacriaEtnaAshFlypoints[] (src/sys_flags.c)
Last line printed: TABLES_OK or TABLES_FAILED.
"""
import csv
import os
import re
import sys

HEADER_GUARD_END = '''#ifndef TRINACRIA_TABLE_END_U16
#define TRINACRIA_TABLE_END_U16 0xFFFF
#endif
#ifndef TRINACRIA_TABLE_END_U8
#define TRINACRIA_TABLE_END_U8 0xFF
#endif
'''


def read_csv(path, columns):
    with open(path, encoding='utf-8', newline='') as f:
        rows = list(csv.DictReader(f))
    for i, row in enumerate(rows, start=2):
        for c in columns:
            if not (row.get(c) or '').strip():
                raise ValueError(f'{path}:{i}: empty column {c!r}')
    return rows


def known_symbols(path, prefix):
    names = set()
    with open(path, encoding='utf-8') as f:
        for line in f:
            m = re.match(r'#define\s+(' + prefix + r'\w+)\s', line)
            if m:
                names.add(m.group(1))
    return names


def gen_banks(problems):
    rows = read_csv('data/trinacria/post_resignation_banks.csv', ('pre_bank', 'post_bank'))
    seen = set()
    entries = []
    for row in rows:
        pre, post = int(row['pre_bank']), int(row['post_bank'])
        if pre in seen:
            problems.append(f'post_resignation_banks.csv: bank {pre} listed twice')
        seen.add(pre)
        for b in (pre, post):
            if not any(n.startswith(f'msg_{b:04d}') and n.endswith('.json') for n in os.listdir('files/msgdata/msg')):
                problems.append(f'post_resignation_banks.csv: files/msgdata/msg/msg_{b:04d}*.json does not exist')
        entries.append(f'    {{ {pre}, {post} }},  // {row.get("note", "").strip()}')
    out = ['// GENERATED by tools/trinacria/trinacria_tables.py from data/trinacria/post_resignation_banks.csv',
           '// Do not edit by hand.',
           '#ifndef POKEHEARTGOLD_TRINACRIA_POST_RESIGNATION_BANKS_H',
           '#define POKEHEARTGOLD_TRINACRIA_POST_RESIGNATION_BANKS_H',
           '',
           HEADER_GUARD_END,
           'typedef struct TrinacriaBankPair {',
           '    u16 pre;',
           '    u16 post;',
           '} TrinacriaBankPair;',
           '',
           'static const TrinacriaBankPair sTrinacriaPostBanks[] = {',
           *entries,
           '    { TRINACRIA_TABLE_END_U16, TRINACRIA_TABLE_END_U16 },',
           '};',
           '',
           '#endif // POKEHEARTGOLD_TRINACRIA_POST_RESIGNATION_BANKS_H',
           '']
    return '\n'.join(out)


def gen_ash(problems):
    rows = read_csv('data/trinacria/etna_ash_zone.csv', ('kind', 'symbol'))
    maps_known = known_symbols('include/constants/maps.h', 'MAP_')
    fly_known = known_symbols('include/constants/flypoints.h', 'FLYPOINT_')
    maps, flys = [], []
    for row in rows:
        kind, sym = row['kind'].strip(), row['symbol'].strip()
        if kind == 'map':
            if sym not in maps_known:
                problems.append(f'etna_ash_zone.csv: {sym} is not defined in include/constants/maps.h')
            maps.append(sym)
        elif kind == 'flypoint':
            if sym not in fly_known:
                problems.append(f'etna_ash_zone.csv: {sym} is not defined in include/constants/flypoints.h')
            flys.append(sym)
        else:
            problems.append(f'etna_ash_zone.csv: unknown kind {kind!r}')
    out = ['// GENERATED by tools/trinacria/trinacria_tables.py from data/trinacria/etna_ash_zone.csv',
           '// Do not edit by hand.',
           '#ifndef POKEHEARTGOLD_TRINACRIA_ETNA_ASH_ZONE_H',
           '#define POKEHEARTGOLD_TRINACRIA_ETNA_ASH_ZONE_H',
           '',
           '#include "constants/flypoints.h"',
           '#include "constants/maps.h"',
           '',
           HEADER_GUARD_END,
           'static const u16 sTrinacriaEtnaAshMaps[] = {',
           *[f'    {s},' for s in maps],
           '    TRINACRIA_TABLE_END_U16,',
           '};',
           '',
           'static const u8 sTrinacriaEtnaAshFlypoints[] = {',
           *[f'    {s},' for s in flys],
           '    TRINACRIA_TABLE_END_U8,',
           '};',
           '',
           '#endif // POKEHEARTGOLD_TRINACRIA_ETNA_ASH_ZONE_H',
           '']
    return '\n'.join(out)


def main():
    problems = []
    try:
        banks = gen_banks(problems)
        ash = gen_ash(problems)
    except (OSError, ValueError) as e:
        problems.append(str(e))
    for p in problems:
        print(p)
    if problems:
        print('TABLES_FAILED')
        return 1
    os.makedirs('include/trinacria', exist_ok=True)
    with open('include/trinacria/post_resignation_banks.h', 'w', encoding='utf-8', newline='\n') as f:
        f.write(banks)
    with open('include/trinacria/etna_ash_zone.h', 'w', encoding='utf-8', newline='\n') as f:
        f.write(ash)
    print('wrote include/trinacria/post_resignation_banks.h and include/trinacria/etna_ash_zone.h')
    print('TABLES_OK')
    return 0


if __name__ == '__main__':
    sys.exit(main())
